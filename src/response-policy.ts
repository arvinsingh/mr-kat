export const responsePolicies = Object.fromEntries(
  Object.entries(groups).flatMap(([policy, paths]) => paths.map((path) => [path, policy])),
) as Record<string, ResponsePolicy>;
export function responsePath(i: Interaction): string {
  if (i.isModalSubmit?.() && i.customId.startsWith('warnings:form-revoke:'))
    return 'warnings revoke';
  if (i.isButton?.() && /^uwuPanel:(add|remove):/.test(i.customId))
    return `uwulock ${i.customId.split(':')[1]}`;
  if (i.isChatInputCommand?.()) {
    const sub = i.options.getSubcommand?.(false);
    return `${i.commandName}${sub ? ` ${sub}` : ''}`;
  }
  if (i.isButton?.() && i.customId.startsWith('voice:')) return `voice ${i.customId.split(':')[1]}`;
  if (i.isButton?.() && i.customId.startsWith('automodMode:')) return 'automod mode';
  if (i.isButton?.() && /^confession:(approve|reject):/.test(i.customId))
    return 'confession review';
  if (i.isModalSubmit?.() && i.customId.startsWith('announce:')) return 'announce builder';
  return '';
}
